import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {defaultDocument} from '../src/attestations/layout.js';
import {createAttestations,companySettings,templateErrors,prepareAttestation} from '../src/attestations/model.js';
import {attestationPdf} from '../src/attestations/pdf.js';
const company={id:'demo'},s=companySettings(createAttestations(),'demo');
s.legalName='Société Démo SARL';s.header='Avenue de démonstration\n3027 Sfax';s.fiscalNumber='0000000/A/M/000';
s.documents={current:defaultDocument(),ended:defaultDocument(true)};
assert.deepEqual(templateErrors(s),[]);
const e={id:'e1',companyId:'demo',firstName:'Amira',lastName:'Ben Salah',gender:'femme',cin:'12345678',cinIssueDate:'2018-05-15'};
const c={id:'c1',employeeId:'e1',start:'2023-01-01',end:'2024-12-31',active:false,status:'TERMINE'};
const f={date:'2026-10-30',city:'Sfax',position:'Gestionnaire RH',signerId:s.signerId};
const result=prepareAttestation(s,{...e,status:'inactif'},c,f,company);
assert.ok(prepareAttestation(s,e,{...c,end:''},f,company).errors.some(x=>x.includes('date de fin')));
assert.ok(prepareAttestation(s,e,{...c,end:'2021-01-01'},f,company).errors.some(x=>x.includes('postérieure')));
assert.deepEqual(result.errors,[]);assert.ok(result.snapshot.body.includes('Madame Amira'));assert.ok(result.snapshot.body.includes('31/12/2024'));assert.ok(result.snapshot.documentBlocks[3].shade);
s.documents.ended[3].text='TITRE MODIFIÉ';assert.equal(result.snapshot.documentBlocks[3].text,'ATTESTATION DE TRAVAIL');
assert.ok(prepareAttestation({...s,fiscalNumber:''},e,c,f,company).errors.length);
s.documents.current[4].text=s.documents.current[4].text.replace('{{contrat_debut}}','');assert.ok(templateErrors(s).some(x=>x.includes('Début du contrat')));
writeFileSync('.tmp-attestation-layout.pdf',await attestationPdf({...result.snapshot,reference:'TEST-LAYOUT'}));
console.log('OK : documents complets, civilité, dates, champs société, copie figée et PDF.');
